"""Build bridges-data.js: every bridge in the game's map (issue #139, 23 Nov 2026).

    python tools/make-bridges.py        (reads the OpenStreetMap extracts the map was made from; no download)
    then python build.py

Reads assets/osm/torshov-osm.json (the old +/-800 m square, as generate-surroundings.py) and every district patch's
assets/osm/<name>-osm.json.gz (as tools/make-district.py), keeps every way tagged bridge (not bridge=no) with a highway or
railway tag inside the world (the old square and the patch boxes), and lists what crosses under it: other roads, paths,
railways and waterways that are not on a bridge of the same or a higher layer (a way that only meets it at a shared node is a
junction, not a crossing), and water areas.

Local frame as surroundings-data.js: metres east (x) and south (s) of the address node 59.936404 N 10.776657 E, rounded to
0.1 m like the map data, so a bridge way's points are the very points of the street in the map data.
Output: window.BRIDGES = {attribution, ways: [[id, kind, name, layer, width, [x, s, ...], under]]}, under = [[kind, name,
layer, tunnel (0/1), x, s, dx, ds, width]] (the crossing point and the under-way's direction there; a water area has no
direction).
Map data (c) OpenStreetMap contributors (ODbL).
"""
import gzip
import json
import math
import os
import re

from shapely.geometry import LineString, Point, Polygon
from shapely.strtree import STRtree

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
LAT0, LON0 = 59.936404, 10.776657
KX = 111320 * math.cos(math.radians(LAT0))
local = lambda p: ((p['lon'] - LON0) * KX, -(p['lat'] - LAT0) * 111320)
# The widths the map data gives each kind (tools/make-district.py ROAD_WIDTH; rails as district.js).
WIDTH = {'motorway': 12, 'motorway_link': 7, 'trunk': 12, 'trunk_link': 7, 'primary': 11, 'primary_link': 7, 'secondary': 9, 'secondary_link': 6,
         'tertiary': 8, 'tertiary_link': 6, 'residential': 6.5, 'unclassified': 6, 'living_street': 5, 'service': 3.6, 'pedestrian': 5,
         'footway': 2.4, 'path': 2, 'cycleway': 2.5, 'steps': 2, 'track': 3, 'bridleway': 2, 'construction': 6,
         'rail': 3.6, 'light_rail': 3.6, 'subway': 3.6, 'narrow_gauge': 3, 'tram': 2.6, 'river': 8, 'canal': 6, 'stream': 2, 'ditch': 1.5, 'drain': 1.5}
RAIL = {'rail', 'light_rail', 'subway', 'narrow_gauge', 'tram'}
WATER = {'river', 'canal', 'stream', 'ditch', 'drain'}

# The world: the old square and every district patch's box (from the header each <name>-data.js was written with).
boxes = {'square': (-800, -800, 800, 800)}
for f in sorted(os.listdir(ROOT)):
    if not f.endswith('-data.js'):
        continue
    head = open(os.path.join(ROOT, f), encoding='utf-8').read(300)
    m = re.match(r'/\* Generated by tools/make-district\.py \(([\w-]+), local box (-?\d+) (-?\d+) (-?\d+) (-?\d+)\)', head)
    if m:
        boxes[m.group(1)] = tuple(int(v) for v in m.group(2, 3, 4, 5))
inside = lambda x, s: any(x0 <= x <= x1 and s0 <= s <= s1 for x0, s0, x1, s1 in boxes.values())

ways = {}
sources = [os.path.join(ROOT, 'assets/osm/torshov-osm.json')] + [os.path.join(ROOT, f'assets/osm/{n}-osm.json.gz') for n in boxes if n != 'square']
for path in sources:
    opener = gzip.open if path.endswith('.gz') else open
    with opener(path, 'rt', encoding='utf-8') as fh:
        for e in json.load(fh)['elements']:
            if e['type'] == 'way' and e.get('geometry') and e['id'] not in ways:
                ways[e['id']] = e


def layer(t):
    try:
        return int(float(t.get('layer', 0)))
    except ValueError:
        return 0


def kind_of(t):
    if t.get('highway'):
        return t['highway']
    if t.get('railway') in RAIL:
        return t['railway']
    if t.get('waterway') in WATER:
        return t['waterway']
    return None


lines, waters = [], []
for w in ways.values():
    t = w.get('tags', {})
    pts = [local(p) for p in w['geometry'] if p]
    if len(pts) < 2:
        continue
    if (t.get('natural') == 'water' or t.get('waterway') == 'riverbank') and len(pts) >= 4 and pts[0] == pts[-1]:
        poly = Polygon(pts).buffer(0)
        if not poly.is_empty:
            waters.append((w, poly))
        continue
    k = kind_of(t)
    if k and t.get('area') != 'yes':
        lines.append((w, k, LineString(pts)))
line_tree, water_tree = STRtree([l for _, _, l in lines]), STRtree([p for _, p in waters])


def on_vertex(p, line):
    return any(math.hypot(p.x - x, p.y - y) < .05 for x, y in line.coords)


out = []
for w, k, ln in lines:
    t = w['tags']
    if t.get('bridge', 'no') == 'no' or t.get('tunnel') in ('yes', 'culvert', 'building_passage'):
        continue
    pts = list(ln.coords)
    if not any(inside(x, s) for x, s in pts):
        continue
    L = layer(t)
    under = []
    for q in line_tree.query(ln):
        w2, k2, l2 = lines[q]
        if w2['id'] == w['id'] or not ln.intersects(l2):
            continue
        t2 = w2.get('tags', {})
        if layer(t2) > L or (layer(t2) == L and t2.get('bridge', 'no') != 'no') or (layer(t2) == L and k2 not in WATER and not t2.get('tunnel')):
            continue
        x = ln.intersection(l2)
        for p in getattr(x, 'geoms', [x]):
            if p.geom_type != 'Point' or (on_vertex(p, ln) and on_vertex(p, l2)):
                continue                                  # a shared node: a junction, not a crossing
            d = l2.project(p)
            a, b = l2.interpolate(max(0, d - 1)), l2.interpolate(min(l2.length, d + 1))
            dl = math.hypot(b.x - a.x, b.y - a.y) or 1
            wd = WIDTH.get(k2, 3)
            try:
                wd = float(t2['width']) if k2 in WATER and 'width' in t2 else wd
            except ValueError:
                pass
            under.append([k2, t2.get('name', ''), layer(t2), 1 if t2.get('tunnel') or t2.get('covered') == 'yes' else 0,
                          round(p.x, 1), round(p.y, 1), round((b.x - a.x) / dl, 3), round((b.y - a.y) / dl, 3), wd])
    for q in water_tree.query(ln):
        w2, poly = waters[q]
        if ln.intersects(poly):
            c = ln.intersection(poly).representative_point()
            under.append(['water', w2.get('tags', {}).get('name', ''), 0, 0, round(c.x, 1), round(c.y, 1), 0, 0, 0])
    under.sort(key=lambda u: (u[0], u[4], u[5]))
    out.append([w['id'], k, t.get('name', ''), L, WIDTH.get(k, 3), [round(v, 1) for c in pts for v in c], under])
out.sort(key=lambda b: b[0])
data = {'attribution': 'Map data © OpenStreetMap contributors (ODbL).', 'ways': out}
text = ('/* Generated by tools/make-bridges.py: every bridge in the map and what crosses under it (issue #139). ' + data['attribution'] + ' */\n'
        'window.BRIDGES = ' + json.dumps(data, separators=(',', ':'), ensure_ascii=False) + ';\n')
with open(os.path.join(ROOT, 'bridges-data.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(text)
print(f'bridges-data.js: {len(out)} bridge ways ({sum(1 for b in out if b[6])} with something under them), {len(text) // 1024} KB')
