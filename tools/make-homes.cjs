// The flats for sale (issue #106): node tools/make-homes.cjs  ->  homes-data.js
// Every neighbouring building with a stair tower you can enter (surroundings-data.js `enterable`) has a flat to the left and
// to the right of each of its four landings. This works out how much room the real building outline (OpenStreetMap) leaves
// beside the tower, and from that each flat's size, number of rooms, address and price.
// Tower frame (stairwell.js): x along the facade, z from the back toward the facade (the facade is the line z = 10.32);
// the tower's side walls are at x = -1.45 (left) and 1.665 (right).
const fs = require('node:fs'), path = require('node:path'), root = path.join(__dirname, '..');
globalThis.window = globalThis;
require(path.join(root, 'surroundings-data.js'));
const D = window.SURROUNDINGS;
const XL = -1.45, XA = 1.665, FACADE = 10.32, OUTER = .3, PARTY = .25, MAX_W = 7.2, MAX_D = 12.4, FLOORS = 4;
const KR_PER_M2 = 115, FLOOR_FACTOR = [0, .9, 1, 1.08, 1.16];// higher up costs more (light and view)

const inPoly = (x, z, o) => {let c = false;for (let i = 0, j = o.length - 1; i < o.length; j = i++) if ((o[i][1] > z) !== (o[j][1] > z) && x < (o[j][0] - o[i][0]) * (z - o[i][1]) / (o[j][1] - o[i][1]) + o[i][0]) c = !c;return c;};
const segDist = (p, a, b) => {const dx = b[0] - a[0], ds = b[1] - a[1], L = dx * dx + ds * ds || 1, t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * ds) / L));return Math.hypot(p[0] - a[0] - dx * t, p[1] - a[1] - ds * t);};
const pairs = f => {const o = [];for (let i = 0; i < f.length; i += 2) o.push([f[i], f[i + 1]]);return o;};
const round = (v, n = 2) => Math.round(v * 10 ** n) / 10 ** n;

const homes = [], LETTERS = 'ABCDEFGH';
D.enterable.forEach((e, t) => {
  const b = D.buildings[e.b], c = Math.cos(e.rot), s = Math.sin(e.rot);
  const outline = pairs(b.r.o).map(([x, z]) => {const dx = x - e.x, dz = z - e.s;return [dx * c - dz * s, dx * s + dz * c];});
  // The whole rectangle x0..x1, z0..z1 lies in the building (its edge checked every 0.2 m).
  const fits = (x0, x1, z0, z1) => {
    for (let x = x0; x <= x1 + 1e-9; x += Math.min(.2, x1 - x0)) if (!inPoly(x, z0, outline) || !inPoly(x, z1, outline)) return false;
    for (let z = z0; z <= z1 + 1e-9; z += .2) if (!inPoly(x0, z, outline) || !inPoly(x1, z, outline)) return false;
    return true;
  };
  // The street this stair's door opens on: the nearest named street to the door (local map metres).
  const door = [e.x + .75 * c + 12.3 * s, e.s - .75 * s + 12.3 * c];
  let street = '', best = Infinity;
  for (const r of D.roads) {if (!r.n || !['residential', 'tertiary', 'secondary', 'unclassified', 'living_street', 'pedestrian', 'service'].includes(r.k)) continue;const p = pairs(r.p);for (let i = 0; i + 1 < p.length; i++) {const d = segDist(door, p[i], p[i + 1]);if (d < best) {best = d;street = r.n;}}}
  for (const side of [-1, 1]) {
    const wall = side < 0 ? XL : XA;
    // Width: out from the tower wall while the facade stays the building's own outer wall and the rooms stay inside it
    // (checked from the facade 9.6 m back, so a slanting party wall gives a narrower flat, not a shallow one).
    let W = 0;
    for (let w = 3; w <= MAX_W + 1e-9; w += .05) {
      const xa = side < 0 ? wall - w - PARTY : wall, xb = side < 0 ? wall : wall + w + PARTY;
      const far = side < 0 ? xa : xb;
      if (!fits(Math.min(xa, xb), Math.max(xa, xb), .7, FACADE - .02) || inPoly(far, FACADE + .15, outline)) break;
      W = w;
    }
    if (W < 3.6) continue;// too narrow for a flat
    W = round(W - .05, 2);
    const x0 = side < 0 ? wall - W : wall, x1 = side < 0 ? wall : wall + W;
    // Depth: back from the facade while the rooms (and the back wall) stay inside the building.
    let back = 4;
    for (let z = 4; z >= FACADE - OUTER - MAX_D - 1e-9; z -= .05) {if (!fits(x0 - (side < 0 ? PARTY : 0), x1 + (side > 0 ? PARTY : 0), z - OUTER, FACADE - .02)) break;back = z;}
    const vb = round(back + .02, 2), vf = round(FACADE - OUTER, 2), depth = vf - vb;
    if (depth < 9) continue;
    const area = Math.round(W * depth), rooms = W >= 6.4 ? 3 : 2;
    for (let n = 1; n <= FLOORS; n++) {
      const price = Math.round(area * KR_PER_M2 * FLOOR_FACTOR[n] / 100) * 100;
      homes.push({id: `b${t}-${n}${side < 0 ? 'L' : 'R'}`, t, n, side, W, vb, vf, area, rooms, price,
        unit: `H0${n}0${side < 0 ? 1 : 2}`, stair: LETTERS[t], street});
    }
  }
});

const head = `/* Generated by tools/make-homes.cjs from surroundings-data.js (map data © OpenStreetMap contributors, ODbL). The flats for sale
 * (issue #106): one to the left and one to the right of every landing in the eight neighbouring stair towers.
 * {id, t (tower = index in SURROUNDINGS.enterable), n (floor 1–4), side (-1 left, 1 right of the stair, seen from the back wall),
 *  W (room width beside the tower wall, m), vb / vf (inner back and front wall, tower z), area (m²), rooms, price (kr),
 *  unit (the Norwegian flat number on the door), stair (the game's letter for the stair tower), street}
 * Also read by the server (cloud/src/homes.js) for the ids and prices. */
`;
const body = `(function (root, list) {if (typeof module === 'object' && module.exports) module.exports = list;else root.HOMES = list;})(typeof window === 'undefined' ? globalThis : window, ${JSON.stringify(homes)});\n`;
fs.writeFileSync(path.join(root, 'homes-data.js'), head + body);
console.log(`${homes.length} flats in ${new Set(homes.map(h => h.t)).size} stair towers, ${Math.min(...homes.map(h => h.area))}–${Math.max(...homes.map(h => h.area))} m², ${Math.min(...homes.map(h => h.price))}–${Math.max(...homes.map(h => h.price))} kr`);
for (const h of homes.filter(h => h.n === 1)) console.log(` ${h.id} ${h.stair} ${h.street} W ${h.W} depth ${(h.vf - h.vb).toFixed(2)} (vb ${h.vb}) ${h.area} m² ${h.rooms} rooms ${h.price} kr`);
